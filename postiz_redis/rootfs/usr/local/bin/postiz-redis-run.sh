#!/usr/bin/env bash
# -----------------------------------------------------------------------------
# Postiz Redis app - start script.
#
# Writes a redis.conf from the app options (password never on the command
# line), then hands over to the official image's docker-entrypoint.sh, which
# fixes ownership, steps down to the "redis" user with gosu and execs
# redis-server as PID 1 (init: false). SIGTERM -> Redis shuts down cleanly
# (and saves a snapshot first when persistence is enabled).
# -----------------------------------------------------------------------------
set -euo pipefail

export POSTIZ_HA_COMPONENT="postiz-redis"
# shellcheck source=SCRIPTDIR/../lib/postiz-ha/common.sh
source /usr/local/lib/postiz-ha/common.sh

log "Starting Postiz Redis app (Redis ${REDIS_VERSION:-?})."

REDIS_PASSWORD="$(opt password)"
require_password "Redis password" "${REDIS_PASSWORD}" "password"

MAXMEMORY_MB="$(opt maxmemory_mb 128)"
case "${MAXMEMORY_MB}" in
    '' | *[!0-9]*) die "maxmemory_mb must be a whole number." ;;
esac
PERSISTENCE="$(opt_bool persistence false)"

DATA_DIR="/data/redis"
CONF_DIR="/run/postiz-redis"
CONF="${CONF_DIR}/redis.conf"

mkdir -p "${DATA_DIR}" "${CONF_DIR}"

umask 0077
{
    echo "# Generated by the Postiz Redis app on every start - do not edit."
    echo "bind * -::*"
    echo "port 6379"
    echo "protected-mode yes"
    echo "requirepass ${REDIS_PASSWORD}"
    echo "dir ${DATA_DIR}"
    echo "dbfilename dump.rdb"
    echo "appendonly no"
    echo "maxmemory ${MAXMEMORY_MB}mb"
    # Postiz keeps only short-lived, re-creatable data in Redis (rate-limit
    # counters, OAuth state, upload tickets, caches), so evicting the least
    # recently used key under memory pressure is preferable to errors.
    echo "maxmemory-policy allkeys-lru"
    echo "loglevel notice"
    if [ "${PERSISTENCE}" = "true" ]; then
        echo "save 3600 1 300 100 60 10000"
    else
        echo 'save ""'
    fi
} > "${CONF}"
chown -R redis:redis "${CONF_DIR}" "${DATA_DIR}"
chmod 0600 "${CONF}"
unset REDIS_PASSWORD SUPERVISOR_TOKEN HASSIO_TOKEN

if [ "${PERSISTENCE}" = "true" ]; then
    log "Persistence: RDB snapshots in ${DATA_DIR} (included in Home Assistant backups)."
else
    log "Persistence: off (Postiz stores only short-lived data in Redis; this is the recommended setting)."
    rm -f "${DATA_DIR}/dump.rdb"
fi
log "Memory limit: ${MAXMEMORY_MB} MB (allkeys-lru). Password authentication: on."
log "Starting redis-server on port 6379 (internal Supervisor network only)."

cd "${DATA_DIR}"
exec docker-entrypoint.sh redis-server "${CONF}"
